// `rustybuns dev` for a Worker with a `connect()` export (worker.connect, #5506). Alchemy's local workerd
// serves a Worker over HTTP only, so dev opens the TCP port itself: each connection on worker.connect.port
// becomes a WebSocket to the dev Worker's CONNECT_PATH, where a dev-only entry (written here, in front of
// the app's own) hands it to `connect()` (connect-worker.ts). A deploy ships the app's entry untouched.
import { createServer, type Server } from "node:net";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { CONNECT_PATH, END } from "./connect-worker.ts";
import type { RustyBunsConfig } from "./config.ts";

/** Alchemy's own default dev port; the bridge pins the Worker to it when it's free, else to a free one. */
export const DEV_HTTP_PORT = 1337;

/** The dev entry's file name, beside the built bundle (or in .rustybuns for an unbuilt main). */
export const DEV_ENTRY = "rb-connect-dev.js";

/**
 * Write the dev entry: it re-exports the app (its Durable Objects and entrypoints) and puts
 * `withConnect` in front of the default export. A prebuilt bundle (`bundle: false`) loads its
 * sibling modules as they are, so the entry goes beside it; an unbuilt main is bundled from
 * .rustybuns. Returns the entry's path, relative to the app.
 */
export function writeConnectEntry(w: NonNullable<RustyBunsConfig["worker"]>, root = "."): string {
  const main = w.builtMain ?? w.main;
  if (!main) throw new Error("worker.connect needs worker.main: the connect() handler is the Worker's own export");
  const dir = w.builtMain ? dirname(w.builtMain) : ".rustybuns";
  const app = w.builtMain ? `./${basename(w.builtMain)}` : relative(dir, main).replace(/^(?!\.)/, "./");
  mkdirSync(join(root, dir), { recursive: true });
  const src = readFileSync(new URL("./connect-worker.ts", import.meta.url), "utf8");
  writeFileSync(join(root, dir, "rb-connect.js"), new Bun.Transpiler({ loader: "ts" }).transformSync(src));
  writeFileSync(join(root, dir, DEV_ENTRY), `// GENERATED by rustybuns dev (worker.connect): the app's entry, with its TCP bridge in front.
import worker from ${JSON.stringify(app)};
import { withConnect } from "./rb-connect.js";
export * from ${JSON.stringify(app)};
export default withConnect(worker);
`);
  return join(dir, DEV_ENTRY);
}

/** True when nothing listens on `port` here. */
export function portFree(port: number): Promise<boolean> {
  return new Promise((ok) => {
    const s = createServer().once("error", () => ok(false)).listen(port, "127.0.0.1", () => s.close(() => ok(true)));
  });
}

/**
 * Listen on `port` and carry each TCP connection to `wsUrl` (the dev Worker's CONNECT_PATH) and back.
 * A FIN from the client goes on as the END frame, and the Worker's END as a FIN, so half-open
 * protocols (git over ssh) work. Resolves once listening.
 */
export function bridgeConnect(port: number, wsUrl: string): Promise<Server> {
  const server = createServer({ allowHalfOpen: true }, (tcp) => {
    const ws = new WebSocket(wsUrl);
    ws.binaryType = "arraybuffer";
    const early: (Uint8Array<ArrayBuffer> | string)[] = [];
    const send = (d: Uint8Array<ArrayBuffer> | string) => ws.readyState === WebSocket.OPEN ? ws.send(d) : early.push(d);
    tcp.on("data", (d: Buffer) => send(Uint8Array.from(d)));
    tcp.on("end", () => send(END));
    tcp.on("error", () => ws.close());
    tcp.on("close", () => ws.close());
    ws.onopen = () => { for (const d of early.splice(0)) ws.send(d); };
    ws.onmessage = (e) => {
      if (typeof e.data === "string") { if (e.data === END) tcp.end(); return; }
      if (e.data instanceof ArrayBuffer) tcp.write(new Uint8Array(e.data));
    };
    // The Worker's connect() settled (or the dev Worker went away): the connection is over.
    ws.onclose = () => tcp.end(() => tcp.destroy());
    ws.onerror = () => tcp.destroy();
  });
  return new Promise((ok, fail) => {
    server.once("error", fail).listen(port, "127.0.0.1", () => ok(server));
  });
}

/** The dev Worker's bridge URL on `httpPort`. */
export const connectUrl = (httpPort: number) => `ws://127.0.0.1:${httpPort}${CONNECT_PATH}`;
