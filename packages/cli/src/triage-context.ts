// What `rustybuns triage` tells the agent about this project before it asks anything: versions, the
// config's targets, the box's URL and whether it answers, its memory, and where everything lives.
// Never a secret's value: only whether one is set.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { release } from "node:os";
import { join } from "node:path";
import type { RustyBunsConfig } from "./config.ts";
import { PROF_SECRET, boxUrl } from "./prof.ts";
import { sharedStateBase } from "./state.ts";
import { probe } from "./triage.ts";

export interface RustyBunsContextInput {
  cwd: string;
  version: string;
  /** The loaded config, null with none, or why it didn't load. */
  cfg: RustyBunsConfig | null | { error: string };
  stage: string;
  env: Record<string, string | undefined>;
  now?: Date;
  send?: typeof fetch;
}

/** Each @rustybuns package under node_modules here or in a parent, with its version. */
export function installedPackages(cwd: string): { name: string; version: string; dir: string }[] {
  for (let dir = cwd; ; dir = join(dir, "..")) {
    const scope = join(dir, "node_modules", "@rustybuns");
    if (existsSync(scope)) {
      return readdirSync(scope).sort().map((p) => {
        const pkg = join(scope, p);
        let version = "?";
        try { version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version; } catch {}
        return { name: `@rustybuns/${p}`, version, dir: pkg };
      });
    }
    if (join(dir, "..") === dir) return [];
  }
}

function memLine(text: string): string {
  try {
    const m = JSON.parse(text);
    const slope = m.slopeMbPerHour === null ? "slope not known yet (needs 3 samples, 5 minutes apart)" : `${m.slopeMbPerHour >= 0 ? "+" : ""}${m.slopeMbPerHour} MB/h`;
    return `rss ${m.rssMb} MB, heap ${m.heapMb} MB, peak ${m.peakRssMb} MB, ${slope}` +
      (m.maxMb ? `, ceiling ${m.maxMb} MB${m.hoursToMax !== null ? ` (~${m.hoursToMax}h away)` : ""}` : ", no ceiling") +
      `, up ${Math.round(m.uptimeS / 60)} min${m.boots ? `, ${m.boots} boots on this disk` : ""}`;
  } catch { return "answered, but not with the memory numbers"; }
}

export async function rustybunsContext(o: RustyBunsContextInput): Promise<string> {
  const at = (p: string) => join(o.cwd, p);
  const has = (p: string) => (existsSync(at(p)) ? "" : " (not there)");
  const cfg = o.cfg && !("error" in o.cfg) ? o.cfg : null;
  const lines: string[] = [
    "# RustyBuns triage context", "",
    `Generated by \`rustybuns triage\` at ${(o.now ?? new Date()).toISOString()}.`, "",
    `- rustybuns: ${o.version}`,
    `- Bun: ${typeof Bun !== "undefined" ? Bun.version : "not Bun"}; Node API ${process.version}`,
    `- OS: ${process.platform} ${process.arch} (${release()})`,
    `- Project: ${o.cwd}`,
    `- Config: ${o.cfg === null ? "no rustybuns.config.ts here (run triage from the app's folder, or `rustybuns init` makes one)" : "error" in o.cfg ? `rustybuns.config.ts failed to load: ${o.cfg.error}` : `rustybuns.config.ts, app \`${cfg!.name}\``}`,
    `- Repo: https://github.com/QuinnsCode/RustyBuns`,
  ];
  if (cfg) {
    const t = cfg.targets ?? {};
    const targets = [t.edge && `edge (Cloudflare${t.edge.domain ? `, ${t.edge.domain}` : ""})`, t.box && `box (${t.box.provider})`, t.desktop && "desktop"].filter(Boolean);
    lines.push(`- Targets: ${targets.join(", ") || "none"}`, `- Alchemy stage: ${o.stage}`, `- Deploy state: ${cfg.state === "project" ? "in the project" : "shared across worktrees"}`);
    if (t.box) {
      const url = boxUrl(o.cwd, cfg, o.stage);
      lines.push("", "## The box", "");
      if (!url) lines.push(`- URL: none in the Alchemy state for stage ${o.stage}: not deployed from here, or under another stage`);
      else {
        const [health, mem] = await Promise.all([probe(`${url}/health`, {}, 5000, o.send), probe(`${url}/__rb/mem`, {}, 5000, o.send)]);
        lines.push(`- URL: ${url}`, `- /health: ${health.line}`, `- /__rb/mem: ${mem.ok ? memLine(mem.text) : mem.line}`);
      }
      lines.push(`- ${PROF_SECRET}: ${o.env[PROF_SECRET] ? "set here (`rustybuns prof` can profile the box)" : cfg.bindings?.[PROF_SECRET] ? "declared, but not set in this shell or .dev.vars" : "not declared: `rustybuns prof` needs it in the config, and a deploy"}`);
    }
  }
  const packages = installedPackages(o.cwd);
  lines.push("", "## Installed RustyBuns packages (the exact source the user runs)", "",
    ...(packages.length ? packages.map((p) => `- ${p.name} ${p.version}: ${p.dir}`) : ["- none under node_modules here or above"]));
  const prof = at(".rustybuns/prof");
  const profiles = existsSync(prof) ? readdirSync(prof).filter((f) => f.endsWith(".cpuprofile")).length : 0;
  const shared = cfg && cfg.state !== "project" ? sharedStateBase(o.cwd) : null;
  lines.push("", "## Paths", "",
    `- Config: ${at("rustybuns.config.ts")}${has("rustybuns.config.ts")}`,
    `- Generated (\`rustybuns generate\` rewrites it): ${at(".rustybuns")}${has(".rustybuns")}`,
    `- CPU profiles from \`rustybuns prof\`: ${prof} (${profiles})`,
    `- Alchemy state: ${shared ? join(shared, "state") : at(".alchemy/state")}`,
    `- wrangler.jsonc: ${at("wrangler.jsonc")}${has("wrangler.jsonc")}`,
    `- package.json: ${at("package.json")}${has("package.json")}`,
    `- Secrets (NEVER read): ${at(".dev.vars")}, ${at(".env")}*, and any op:// reference's value`,
  );
  return lines.join("\n") + "\n";
}
