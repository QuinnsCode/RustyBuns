// Counts the UI drift per app (#3178): hand-rolled button rules, dialogs, toasts, colour literals, emojis.
// `bun scripts/ui-inventory.ts` prints a markdown table, worst drift first; `--write` puts it in docs/UI_INVENTORY.md.
import { Glob } from "bun";
import { readdirSync } from "node:fs";

const COUNTS: [string, RegExp][] = [
  ["button rules", /(^|[\s,}])(button|\.btn[\w-]*|\.button)\s*(\{|,|:hover)/gm],
  ["dialogs", /role[=:]\s*["']dialog["']|class(Name)?=["'][^"']*(modal|dialog|sheet)/g],
  ["toasts", /\btoast\b/gi],
  ["colours", /#[0-9a-fA-F]{6}\b/g],
  ["emojis", /\p{Extended_Pictographic}/gu],
];
const rows: { app: string; n: number[]; colours: number }[] = [];
for (const app of readdirSync("apps").sort()) {
  const n = COUNTS.map(() => 0);
  const seen = new Set<string>();
  for await (const f of new Glob(`apps/${app}/**/*.{ts,tsx,css,html,svelte,vue,astro}`).scan()) {
    if (/node_modules|\/dist\/|\.test\.|\/test\//.test(f)) continue;
    const text = await Bun.file(f).text();
    COUNTS.forEach(([name, re], i) => {
      const m = text.match(re) ?? [];
      n[i] += name === "colours" ? 0 : m.length;
      if (name === "colours") m.forEach((c) => seen.add(c.toLowerCase()));
    });
  }
  n[3] = seen.size; // distinct colour literals, not occurrences
  rows.push({ app, n, colours: seen.size });
}
rows.sort((a, b) => b.n.reduce((s, x) => s + x, 0) - a.n.reduce((s, x) => s + x, 0));
const out = [`| app | ${COUNTS.map(([n]) => n).join(" | ")} |`, `|---|${COUNTS.map(() => "--:").join("|")}|`, ...rows.filter((r) => r.n.some(Boolean)).map((r) => `| ${r.app} | ${r.n.join(" | ")} |`)].join("\n");
if (process.argv.includes("--write")) await Bun.write("docs/UI_INVENTORY.md", `# UI drift by app\n\nGenerated by \`bun scripts/ui-inventory.ts --write\` (#3178). Colours are distinct hex literals; the rest are occurrences. Mark each app's elements thematic or drift by hand in the migration issue.\n\n${out}\n`);
else console.log(out);
