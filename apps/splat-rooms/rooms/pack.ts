// Packs raw splats into splat-transform's "compressed PLY", the format InteriorGS ships and both PlayCanvas
// (Splat Rooms) and Splat Spray's decoder read: chunks of 256 splats, each with min/max bounds, and 16 bytes
// a splat (11/10/11 position and log scale, smallest-three rotation, 8-bit colour and alpha).
// Splats are sorted along a Morton curve first so each chunk is a small patch of room and keeps precision.

/** One row per splat: x y z, sx sy sz (linear), qw qx qy qz, r g b (0..1), a (0..1). */
export const ROW = 14;
const CHUNK = 256;

const FIELDS = ["min_x", "min_y", "min_z", "max_x", "max_y", "max_z", "min_scale_x", "min_scale_y", "min_scale_z",
  "max_scale_x", "max_scale_y", "max_scale_z", "min_r", "min_g", "min_b", "max_r", "max_g", "max_b"];

function spread10(v: number): number {
  v &= 0x3ff;
  v = (v | (v << 16)) & 0x030000ff;
  v = (v | (v << 8)) & 0x0300f00f;
  v = (v | (v << 4)) & 0x030c30c3;
  v = (v | (v << 2)) & 0x09249249;
  return v;
}

function mortonOrder(rows: Float32Array, n: number): Uint32Array {
  const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < n; i++) for (let a = 0; a < 3; a++) {
    const v = rows[i * ROW + a]!;
    if (v < lo[a]!) lo[a] = v;
    if (v > hi[a]!) hi[a] = v;
  }
  const code = new Uint32Array(n);
  for (let i = 0; i < n; i++) {
    let c = 0;
    for (let a = 0; a < 3; a++) {
      const t = (rows[i * ROW + a]! - lo[a]!) / (hi[a]! - lo[a]! || 1);
      c |= spread10(Math.min(1023, Math.floor(t * 1024))) << a;
    }
    code[i] = c >>> 0;
  }
  const order = new Uint32Array(n);
  for (let i = 0; i < n; i++) order[i] = i;
  return order.sort((p, q) => code[p]! - code[q]!);
}

const q = (t: number, bits: number) => Math.max(0, Math.min((1 << bits) - 1, Math.round(t * ((1 << bits) - 1))));
const norm = (v: number, lo: number, hi: number) => (hi - lo > 0 ? (v - lo) / (hi - lo) : 0);

export function packPly(rows: Float32Array): Uint8Array {
  const n = Math.floor(rows.length / ROW);
  const order = mortonOrder(rows, n);
  const chunks = Math.ceil(n / CHUNK);
  const head = ["ply", "format binary_little_endian 1.0", "comment Generated by splat-rooms rooms/pack.ts",
    `element chunk ${chunks}`, ...FIELDS.map((f) => `property float ${f}`),
    `element vertex ${n}`, "property uint packed_position", "property uint packed_rotation",
    "property uint packed_scale", "property uint packed_color", "end_header", ""].join("\n");
  // the float chunk table must start on a 4-byte boundary, so pad the comment until the header does
  const headBytes = new TextEncoder().encode(head.replace("pack.ts\n", "pack.ts" + " ".repeat((4 - (head.length % 4)) % 4) + "\n"));
  const out = new Uint8Array(headBytes.length + chunks * 18 * 4 + n * 16);
  out.set(headBytes);
  const cd = new Float32Array(out.buffer, headBytes.length, chunks * 18);
  const vd = new DataView(out.buffer, headBytes.length + chunks * 18 * 4);

  const ls = new Float32Array(3);
  for (let c = 0; c < chunks; c++) {
    const from = c * CHUNK, to = Math.min(n, from + CHUNK);
    const m = new Float32Array(18);
    for (let a = 0; a < 3; a++) { m[a] = m[6 + a] = m[12 + a] = Infinity; m[3 + a] = m[9 + a] = m[15 + a] = -Infinity; }
    for (let k = from; k < to; k++) {
      const r = order[k]! * ROW;
      for (let a = 0; a < 3; a++) {
        const p = rows[r + a]!, s = Math.log(Math.max(rows[r + 3 + a]!, 1e-7)), col = rows[r + 10 + a]!;
        m[a] = Math.min(m[a]!, p); m[3 + a] = Math.max(m[3 + a]!, p);
        m[6 + a] = Math.min(m[6 + a]!, s); m[9 + a] = Math.max(m[9 + a]!, s);
        m[12 + a] = Math.min(m[12 + a]!, col); m[15 + a] = Math.max(m[15 + a]!, col);
      }
    }
    cd.set(m, c * 18);
    for (let k = from; k < to; k++) {
      const r = order[k]! * ROW;
      for (let a = 0; a < 3; a++) ls[a] = Math.log(Math.max(rows[r + 3 + a]!, 1e-7));
      const pos = (q(norm(rows[r]!, m[0]!, m[3]!), 11) << 21) | (q(norm(rows[r + 1]!, m[1]!, m[4]!), 10) << 11) | q(norm(rows[r + 2]!, m[2]!, m[5]!), 11);
      const scl = (q(norm(ls[0]!, m[6]!, m[9]!), 11) << 21) | (q(norm(ls[1]!, m[7]!, m[10]!), 10) << 11) | q(norm(ls[2]!, m[8]!, m[11]!), 11);
      const col = (q(norm(rows[r + 10]!, m[12]!, m[15]!), 8) << 24) | (q(norm(rows[r + 11]!, m[13]!, m[16]!), 8) << 16) |
        (q(norm(rows[r + 12]!, m[14]!, m[17]!), 8) << 8) | q(rows[r + 13]!, 8);
      // rotation: drop the largest component (its sign made positive), keep the other three at 10 bits
      const qt = [rows[r + 6]!, rows[r + 7]!, rows[r + 8]!, rows[r + 9]!];
      const len = Math.hypot(...qt) || 1;
      let big = 0;
      for (let j = 1; j < 4; j++) if (Math.abs(qt[j]!) > Math.abs(qt[big]!)) big = j;
      const sign = qt[big]! < 0 ? -1 : 1;
      let rot = big << 30, slot = 0;
      for (let j = 0; j < 4; j++) {
        if (j === big) continue;
        rot |= q(((qt[j]! * sign) / len) / Math.SQRT2 + 0.5, 10) << (20 - 10 * slot++);
      }
      const o = k * 16;
      vd.setUint32(o, pos >>> 0, true);
      vd.setUint32(o + 4, rot >>> 0, true);
      vd.setUint32(o + 8, scl >>> 0, true);
      vd.setUint32(o + 12, col >>> 0, true);
    }
  }
  return out;
}
