// Writes migrations/0002_demo.sql from src/demo.ts: the demo org and its products, seeded into D1 on a fresh deploy.
// Run it after changing src/demo.ts. Once a host has applied 0002, a further change goes in a new migration instead.
import { join } from "node:path";
import { help } from "../../../scripts/help.ts";
import { DEMO_ORG, DEMO_PRODUCTS, DEMO_SETTINGS } from "../src/demo.ts";


export function demoSql(): string {
  const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
  const o = DEMO_SETTINGS;
  const rows = Object.entries(DEMO_PRODUCTS).map(([id, p]) => `  (${q(DEMO_ORG)}, ${q(id)}, ${q(JSON.stringify(p))}, 0)`);
  return [
    "-- GENERATED by scripts/demo-sql.ts from src/demo.ts: the public demo org and its products. Don't hand-edit.",
    "INSERT OR IGNORE INTO orgs (id, origins, admins, samples, studio, read_only, updated) VALUES",
    `  (${q(DEMO_ORG)}, ${q(JSON.stringify(o.origins))}, ${q(JSON.stringify(o.admins ?? []))}, ${o.samples ?? 0}, NULL, ${o.readOnly ? 1 : 0}, 0);`,
    "INSERT OR IGNORE INTO products (org, id, body, updated) VALUES",
    `${rows.join(",\n")};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  help(import.meta.path);
  const out = join(import.meta.dir, "../migrations/0002_demo.sql");
  await Bun.write(out, demoSql());
  console.log(`wrote ${out}`);
}
