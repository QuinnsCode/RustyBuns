import { afterAll, describe, expect, setDefaultTimeout, test } from "bun:test";
import { apply, empty, fromText, merge, text, type Doc } from "../src/lines.ts";
import { diffToOps } from "../src/sync.ts";
import { DEFAULTS, policyOf } from "../src/policy.ts";
import { local as boot } from "../src/local.ts";

// End to end (in-process D1 and file DOs): fine alone, slow on a busy machine.
setDefaultTimeout(20_000);

const opened: { close(): void }[] = [];
afterAll(() => { for (const o of opened) o.close(); });

describe("policy per path (#938)", () => {
  test("defaults by kind: lockfiles locked and regenerated by CI, config and prose to an AI, code to a person", () => {
    expect(policyOf("bun.lock")).toEqual({ live: "locked", merge: "lock", leftover: "ci" });
    expect(policyOf("src/features.json")).toEqual(DEFAULTS.keyed);
    expect(policyOf("README.md")).toEqual({ live: "free", merge: "prose", leftover: "ai" });
    expect(policyOf("src/worker.ts")).toEqual({ live: "free", merge: "code", leftover: "person" });
  });

  test(".gitattributes overrides the hot spots, a later line winning", () => {
    const attrs = [
      "# hot spots",
      "*.json codesplitter-live=line",
      "src/features.json codesplitter-leftover=person",
      "CHANGELOG.md merge=union",
      "*.png -merge",
      "docs/**/*.md codesplitter-merge=code codesplitter-live=nonsense",
      "*.txt text eol=lf",
    ].join("\n");
    expect(policyOf("src/features.json", attrs)).toEqual({ live: "line", merge: "keyed", leftover: "person" });
    expect(policyOf("a/b/package.json", attrs)).toEqual({ live: "line", merge: "keyed", leftover: "ai" });
    // A slash anchors the pattern at the top.
    expect(policyOf("x/src/features.json", attrs).leftover).toBe("ai");
    expect(policyOf("CHANGELOG.md", attrs).merge).toBe("union");
    expect(policyOf("img/logo.png", attrs).merge).toBe("lock");
    expect(policyOf("docs/guide/a.md", attrs)).toEqual({ live: "free", merge: "code", leftover: "ai" });
    expect(policyOf("notes.txt", attrs)).toEqual(DEFAULTS.prose);
  });

  test("merge=union keeps both sides of a line both rewrote, main's first, and a line both added once", () => {
    const main = empty();
    apply(main, fromText("# Changes\n- one"), "me");
    const base = structuredClone(main), branch = structuredClone(main);
    apply(main, diffToOps(main.lines, ["# Changes", "- two", "- same"]), "ana");
    apply(branch, diffToOps(branch.lines, ["# Changes", "- three", "- same"]), "bot");
    expect(merge(base, branch, main, {}, "bot", "CHANGELOG.md").conflicts.length).toBeGreaterThan(0);
    const m = merge(base, branch, main, {}, "bot", "CHANGELOG.md", "bot", "union");
    expect(m.conflicts).toEqual([]);
    expect(apply(main, m.ops, m.by, 0, main.rev).ok).toBe(true);
    expect(text(main)).toBe("# Changes\n- two\n- same\n- three");
  });

  test("union still refuses conflict markers", () => {
    const main = empty();
    apply(main, fromText("a\nb"), "me");
    const base = structuredClone(main), branch = structuredClone(main);
    apply(branch, diffToOps(branch.lines, ["a", "<<<<<<< HEAD", "b", ">>>>>>> x"]), "bot");
    expect(merge(base, branch, main, {}, "bot", "notes.md", "bot", "union").conflicts.map((c) => c.line)).toEqual(["lint:markers"]);
  });

  test("over the API: the repo's .gitattributes sets the merge rule, and the review shows each file's policy", async () => {
    const call = await boot({ GH_CLI: "off" });
    opened.push(call);
    const post = (url: string, body: unknown) => call("ana", url, { method: "POST", body: JSON.stringify(body) });
    await post("/api/login", { name: "ana" });
    await post("/api/repos", { name: "r" });
    await post("/api/repos/ana/r/files", { path: ".gitattributes", content: "CHANGELOG.md merge=union" });
    await post("/api/repos/ana/r/files", { path: "CHANGELOG.md", content: "# Changes\n- one" });
    await post("/api/repos/ana/r/branches", { name: "b1" });
    await post("/api/repos/ana/r/do/ops?path=CHANGELOG.md&branch=b1", { ops: [{ kind: "set", line: "L2", base: 2, text: "- three" }] });
    await post("/api/repos/ana/r/do/ops?path=CHANGELOG.md", { ops: [{ kind: "set", line: "L2", base: 2, text: "- two" }] });
    const review = await (await call("ana", "/api/repos/ana/r/branches/b1")).json() as any;
    expect(review.files[0]).toMatchObject({ path: "CHANGELOG.md", policy: { live: "free", merge: "union", leftover: "ai" }, conflicts: [] });
    expect((await post("/api/repos/ana/r/branches/b1/merge", {})).status).toBe(200);
    const doc = await (await call("ana", "/api/repos/ana/r/do/file?path=CHANGELOG.md")).json() as Doc;
    expect(text(doc)).toBe("# Changes\n- two\n- three");
  });
});
