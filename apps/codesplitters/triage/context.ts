// What `codesplitters triage` tells the agent before it asks anything: versions, the site and whether
// it answers, who the token signs in as, and where things live. Never the token itself.
import { existsSync } from "node:fs";
import { homedir, release } from "node:os";
import { join } from "node:path";
import { probe } from "@rustybuns/cli/triage";
import { tool, toRequest } from "../src/mcp.ts";

export interface SplittersContextInput {
  /** The site, and where it came from. */
  url?: string;
  urlFrom?: string;
  token?: string;
  tokenFrom?: string;
  as?: string;
  configPath: string;
  send?: typeof fetch;
  now?: Date;
}

export async function splittersContext(o: SplittersContextInput): Promise<string> {
  const runtime = typeof (globalThis as any).Bun !== "undefined" ? `Bun ${(globalThis as any).Bun.version}` : `Node ${process.version}`;
  const lines = [
    "# codeSplitters triage context", "",
    `Generated by \`codesplitters triage\` at ${(o.now ?? new Date()).toISOString()}.`, "",
    `- CLI runs on: ${runtime}`,
    `- OS: ${process.platform} ${process.arch} (${release()})`,
    `- Site: ${o.url ? `${o.url} (from ${o.urlFrom})` : "none: set CODESPLITTERS_URL, pass --url, or run `codesplitters login`"}`,
    `- Signed in with: ${o.token ? `an API token (from ${o.tokenFrom}; never print it)` : o.as ? `--as ${o.as} (desktop alias)` : "nothing: no token saved or set"}`,
  ];
  if (o.url) {
    const whoami = tool("whoami")!;
    const headers: Record<string, string> = { "user-agent": "codesplitters-cli/1 triage", ...(o.token ? { authorization: `Bearer ${o.token}` } : o.as ? { cookie: `cs_user=${o.as}` } : {}) };
    const req = toRequest(whoami, {}, o.url, headers) as Request;
    const site = await probe(o.url, {}, 5000, o.send);
    const me = await probe(req.url, { headers }, 5000, o.send);
    lines.push(`- Site answers: ${site.line}`);
    let who = me.line;
    if (me.ok) {
      try {
        const s = JSON.parse(me.text);
        who = !s?.user ? "not signed in: the site sees no session for these credentials" : `${s.user}${s.token ? `, token "${s.token.label}" scope ${s.token.scope}${s.token.expires_at ? `, expires ${new Date(s.token.expires_at).toISOString()}` : ""}` : ""}`;
      } catch {}
    }
    lines.push(`- whoami: ${who}`);
  }
  const desktop = join(homedir(), ".codesplitters");
  lines.push(`- Repo: https://github.com/QuinnsCode/RustyBuns (the app is apps/codesplitters)`, "", "## Paths", "",
    `- CLI config (holds the token: NEVER print or quote it): ${o.configPath}${existsSync(o.configPath) ? "" : " (not there)"}`,
    `- Desktop app data (bare repos, sqlite): ${desktop}${existsSync(desktop) ? "" : " (not there: no desktop app on this machine)"}`,
  );
  return lines.join("\n") + "\n";
}
